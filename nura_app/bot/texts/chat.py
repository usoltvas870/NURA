def messages_remaining_text(remaining: int) -> str:
    if remaining <= 0:
        return "\n\n<i>Это было последнее бесплатное сообщение.</i>"
    plural = "сообщение" if remaining == 1 else "сообщения" if remaining in (2, 3, 4) else "сообщений"
    return f"\n\n<i>Осталось {remaining} бесплатных {plural}.</i>"

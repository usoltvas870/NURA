def report_ready_pwa_text(archetype: str | None = None) -> str:
    base = "✦ Твоя Матрица Судьбы готова!\n\n"
    if archetype:
        base += f"Твой архетип — {escape_telegram_html(archetype)}.\n\n"
    base += "Открой NURA, чтобы увидеть полный разбор."
    return base
